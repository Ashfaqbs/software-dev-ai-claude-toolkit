# software-dev-ai-claude-toolkit installer (Windows PowerShell)
# Copies rules, commands, agents, skills, hooks, and MCP config to ~/.claude/
# by default.
#
# Params:
#   -Stacks <group,group,...>  Install only "general" plus the named stacks,
#                              e.g.: .\install.ps1 -Stacks python-fastapi,ai-ml
#   -Local                    Install into .\.claude in the current directory
#                              (project-scoped) instead of ~/.claude (global,
#                              the default). Also installs .\CLAUDE.md (blank
#                              project template) and .\.mcp.json here instead
#                              of under ~/.claude.
#   -Ai <target>               Target AI tool. Default: claude (full install).
#                              Other targets export the selected rules into
#                              that tool's own format at the project root and
#                              skip commands/agents/skills/hooks/MCP (no
#                              equivalent there yet, except opencode which
#                              also maps commands/agents). See -ListGroups.
#   -ListGroups                Print available -Stacks groups and -Ai targets.

param(
    [string[]]$Stacks = @(),
    [switch]$Local,
    [ValidateSet("claude", "copilot", "cursor", "windsurf", "opencode", "agentsmd")]
    [string]$Ai = "claude",
    [switch]$ListGroups
)

$ErrorActionPreference = "Stop"

$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$Manifest = Get-Content "$ScriptDir\toolkit-manifest.json" -Raw | ConvertFrom-Json

if ($ListGroups) {
    Write-Host "Available -Stacks groups:"
    foreach ($prop in $Manifest.installGroups.PSObject.Properties) {
        Write-Host "  $($prop.Name) - $($prop.Value)"
    }
    Write-Host ""
    Write-Host "Available -Ai targets:"
    foreach ($prop in $Manifest.aiTargets.PSObject.Properties) {
        Write-Host "  $($prop.Name) - $($prop.Value)"
    }
    Write-Host ""
    Write-Host $Manifest.aiTargetsNote
    exit 0
}

function Get-FilteredIds {
    param([string]$ComponentType, [string[]]$WantedStacks)

    $wanted = @("general") + $WantedStacks
    $result = @()
    foreach ($entry in $Manifest.$ComponentType) {
        if ($wanted -contains $entry.group) {
            $result += $entry.id
        }
    }
    return $result
}

$ProjectRoot = Get-Location

function Get-FlattenedRulesLines {
    param([string[]]$RuleIds, [string]$ToolLabel)

    $lines = @(
        "<!-- Generated by software-dev-ai-claude-toolkit install.ps1 $ToolLabel -->",
        "<!-- Source rules flattened below; edit freely, this is a one-time export -->",
        ""
    )
    foreach ($id in $RuleIds) {
        $ruleSrc = Join-Path $ScriptDir "rules\$id.md"
        if (Test-Path $ruleSrc -PathType Leaf) {
            $lines += "## Rule: $id"
            $lines += ""
            $lines += (Get-Content $ruleSrc -Raw)
            $lines += ""
            $lines += "---"
            $lines += ""
        }
    }
    return $lines
}

function Write-FlattenedRulesFile {
    param([string]$DestFile, [string[]]$RuleIds, [string]$ToolLabel)

    New-Item -ItemType Directory -Path (Split-Path -Parent $DestFile) -Force | Out-Null
    if (Test-Path $DestFile) {
        $timestamp = Get-Date -Format "yyyyMMddHHmmss"
        Copy-Item -Path $DestFile -Destination "$DestFile.backup.$timestamp"
        Write-Host "  BACKUP: $(Split-Path -Leaf $DestFile)" -ForegroundColor Yellow
    }
    $lines = Get-FlattenedRulesLines -RuleIds $RuleIds -ToolLabel $ToolLabel
    Set-Content -Path $DestFile -Value ($lines -join "`n") -Encoding UTF8
}

# === Non-claude export paths: flatten/translate the selected rules into the
# target tool's own format, skip the rest (no equivalent there yet, except
# opencode which also maps commands/agents), and exit. All of these always
# write to the current directory regardless of -Local, since none of them
# have a global/user-level config the way Claude Code does.
if ($Ai -ne "claude") {
    Write-Host "=== Software Dev AI Claude Toolkit - Installer ($Ai target) ===" -ForegroundColor Cyan
    Write-Host ""

    $ruleIds = Get-FilteredIds -ComponentType "rules" -WantedStacks $Stacks

    switch ($Ai) {
        "copilot" {
            $destFile = Join-Path $ProjectRoot ".github\copilot-instructions.md"
            Write-FlattenedRulesFile -DestFile $destFile -RuleIds $ruleIds -ToolLabel "-Ai copilot"
            Write-Host "  OK: .github/copilot-instructions.md (flattened from rules)" -ForegroundColor Green
            Write-Host "  SKIPPED (no Copilot equivalent in v1): commands, agents, skills, hooks, MCP config" -ForegroundColor Yellow
        }
        "agentsmd" {
            $destFile = Join-Path $ProjectRoot "AGENTS.md"
            Write-FlattenedRulesFile -DestFile $destFile -RuleIds $ruleIds -ToolLabel "-Ai agentsmd"
            Write-Host "  OK: AGENTS.md (the open AGENTS.md standard - read by Codex, OpenCode, Jules," -ForegroundColor Green
            Write-Host "      Zed, Warp, Aider, goose, Amp, and as a fallback by Cursor/Windsurf/Copilot)" -ForegroundColor Green
            Write-Host "  SKIPPED (no shared equivalent in v1): commands, agents, skills, hooks, MCP config" -ForegroundColor Yellow
        }
        "cursor" {
            $destDir = Join-Path $ProjectRoot ".cursor\rules"
            New-Item -ItemType Directory -Path $destDir -Force | Out-Null
            $n = 0
            foreach ($id in $ruleIds) {
                $ruleSrc = Join-Path $ScriptDir "rules\$id.md"
                if (Test-Path $ruleSrc -PathType Leaf) {
                    $dest = Join-Path $destDir "$id.mdc"
                    $content = "---`ndescription: $id (from software-dev-ai-claude-toolkit)`nalwaysApply: true`n---`n`n" + (Get-Content $ruleSrc -Raw)
                    Set-Content -Path $dest -Value $content -Encoding UTF8
                    $n++
                }
            }
            Write-Host "  OK: .cursor/rules/*.mdc ($n files, alwaysApply: true)" -ForegroundColor Green
            Write-Host "  SKIPPED (no Cursor equivalent in v1): commands, agents, skills, hooks, MCP config" -ForegroundColor Yellow
        }
        "windsurf" {
            $destDir = Join-Path $ProjectRoot ".windsurf\rules"
            New-Item -ItemType Directory -Path $destDir -Force | Out-Null
            $n = 0
            foreach ($id in $ruleIds) {
                $ruleSrc = Join-Path $ScriptDir "rules\$id.md"
                if (Test-Path $ruleSrc -PathType Leaf) {
                    $dest = Join-Path $destDir "$id.md"
                    Copy-Item -Path $ruleSrc -Destination $dest -Force
                    $chars = (Get-Content $dest -Raw).Length
                    if ($chars -gt 6000) {
                        Write-Host "  WARN: $id.md is $chars chars - over Windsurf's ~6000-char-per-file guidance, it may be truncated" -ForegroundColor Yellow
                    }
                    $n++
                }
            }
            Write-Host "  OK: .windsurf/rules/*.md ($n files)" -ForegroundColor Green
            Write-Host "  SKIPPED (no Windsurf equivalent in v1): commands, agents, skills, hooks, MCP config" -ForegroundColor Yellow
        }
        "opencode" {
            $destFile = Join-Path $ProjectRoot "AGENTS.md"
            Write-FlattenedRulesFile -DestFile $destFile -RuleIds $ruleIds -ToolLabel "-Ai opencode"
            Write-Host "  OK: AGENTS.md" -ForegroundColor Green

            $cmdDestDir = Join-Path $ProjectRoot ".opencode\command"
            New-Item -ItemType Directory -Path $cmdDestDir -Force | Out-Null
            $commandFiles = Get-ChildItem (Join-Path $ScriptDir "commands") -Filter "*.md"
            foreach ($f in $commandFiles) {
                Copy-Item -Path $f.FullName -Destination $cmdDestDir -Force
            }
            Write-Host "  OK: .opencode/command/*.md ($($commandFiles.Count) commands, copied as-is - same `$ARGUMENTS convention)" -ForegroundColor Green

            $agentDestDir = Join-Path $ProjectRoot ".opencode\agent"
            New-Item -ItemType Directory -Path $agentDestDir -Force | Out-Null
            $agentFiles = Get-ChildItem (Join-Path $ScriptDir "agents") -Filter "*.md"
            foreach ($f in $agentFiles) {
                $raw = Get-Content $f.FullName -Raw
                $desc = ""
                if ($raw -match "(?s)^---\r?\n(.*?)\r?\n---\r?\n(.*)$") {
                    $frontmatter = $Matches[1]
                    $body = $Matches[2]
                    if ($frontmatter -match "(?m)^description:\s*(.*)$") {
                        $desc = $Matches[1].Trim()
                    }
                } else {
                    $body = $raw
                }
                $out = "---`ndescription: $desc`nmode: subagent`n---`n$body"
                Set-Content -Path (Join-Path $agentDestDir $f.Name) -Value $out -Encoding UTF8
            }
            Write-Host "  OK: .opencode/agent/*.md ($($agentFiles.Count) agents, mode: subagent - model/tools fields dropped," -ForegroundColor Green
            Write-Host "      OpenCode's model ids differ from Claude's; set manually if you need a specific model)" -ForegroundColor Green
            Write-Host "  SKIPPED (no OpenCode equivalent in v1): skills, hooks, MCP config" -ForegroundColor Yellow
        }
    }

    Write-Host ""
    Write-Host "=== Installation Complete ===" -ForegroundColor Cyan
    exit 0
}

